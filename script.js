/*
  FRAME celebrity gallery
  Images are searched on Wikimedia Commons. No API key is required.
  Only strongly name-matched files are shown; no stock/AI fallback is used.
*/
const COMMONS_API = "https://commons.wikimedia.org/w/api.php";
const people = PEOPLE_DATA;
const PAGE_SIZE = 20;
const state = {
  query: "",
  category: "All",
  visible: PAGE_SIZE,
  imageCache: new Map(),
  pending: new Set()
};

const grid = document.getElementById("galleryGrid");
const searchInput = document.getElementById("searchInput");
const resultCount = document.getElementById("resultCount");
const emptyState = document.getElementById("emptyState");
const loadMore = document.getElementById("loadMore");
const apiNotice = document.getElementById("apiNotice");

function initials(name) {
  return name.split(/\s+/).slice(0, 2).map(part => part[0]).join("").toUpperCase();
}

function filteredPeople() {
  const q = state.query.trim().toLocaleLowerCase();
  return people.filter(person => {
    const matchesName = !q || person.name.toLocaleLowerCase().includes(q);
    const matchesCategory = state.category === "All" || person.categories.includes(state.category);
    return matchesName && matchesCategory;
  });
}

function render() {
  const matches = filteredPeople();
  const visible = matches.slice(0, state.visible);
  grid.innerHTML = "";
  visible.forEach(person => grid.appendChild(createCard(person)));
  resultCount.textContent = `${matches.length} ${matches.length === 1 ? "person" : "people"} in the collection`;
  emptyState.hidden = matches.length !== 0;
  loadMore.hidden = matches.length <= state.visible;
  loadVisibleImages();
}

function createCard(person) {
  const card = document.createElement("article");
  card.className = "person-card";

  const wrap = document.createElement("div");
  wrap.className = "photo-wrap";
  wrap.dataset.person = person.name;

  const fallback = document.createElement("div");
  fallback.className = "photo-fallback";
  fallback.textContent = initials(person.name);
  wrap.appendChild(fallback);

  const name = document.createElement("h3");
  name.className = "person-name";
  name.textContent = person.name;

  const meta = document.createElement("p");
  meta.className = "person-meta";
  meta.textContent = person.categories.join(" · ");
  card.append(wrap, name, meta);

  const cached = state.imageCache.get(person.name);
  if (cached) showImage(wrap, cached);
  return card;
}

function showImage(wrap, image) {
  const link = document.createElement("a");
  link.href = image.filePage;
  link.target = "_blank";
  link.rel = "noopener noreferrer";
  link.className = "commons-image-link";
  link.setAttribute("aria-label", `Open ${wrap.dataset.person} image source on Wikimedia Commons`);

  const img = document.createElement("img");
  img.alt = `${wrap.dataset.person} photograph`;
  img.loading = "lazy";
  img.decoding = "async";
  img.referrerPolicy = "no-referrer";
  img.src = image.thumb;
  img.onerror = () => {
    link.remove();
    if (!wrap.querySelector(".photo-fallback")) {
      const fallback = document.createElement("div");
      fallback.className = "photo-fallback";
      fallback.textContent = initials(wrap.dataset.person);
      wrap.prepend(fallback);
    }
  };

  const badge = document.createElement("span");
  badge.className = "photo-source";
  badge.textContent = "WIKIMEDIA COMMONS";
  link.append(img, badge);
  wrap.replaceChildren(link);
}

function normalize(value) {
  return value.toLocaleLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, " ").trim();
}

function isStrongNameMatch(title, name) {
  const fileTitle = normalize(title.replace(/^File:/i, ""));
  const target = normalize(name);
  if (fileTitle.includes(target)) return true;

  // Require the full surname and at least one other name token to reduce false matches.
  const parts = target.split(" ");
  if (parts.length < 2) return fileTitle.includes(target);
  return fileTitle.includes(parts[parts.length - 1]) &&
    parts.slice(0, -1).some(part => fileTitle.includes(part));
}

async function findCommonsImage(name) {
  const params = new URLSearchParams({
    action: "query",
    generator: "search",
    gsrsearch: `"${name}"`,
    gsrnamespace: "6",
    gsrlimit: "12",
    prop: "imageinfo",
    iiprop: "url|extmetadata",
    iiurlwidth: "700",
    format: "json",
    origin: "*"
  });

  const response = await fetch(`${COMMONS_API}?${params}`);
  if (!response.ok) throw new Error(`Wikimedia Commons returned ${response.status}`);
  const data = await response.json();
  const pages = Object.values(data.query?.pages || {});

  const match = pages.find(page =>
    page.imageinfo?.[0]?.thumburl &&
    isStrongNameMatch(page.title || "", name)
  );
  if (!match) return null;

  const info = match.imageinfo[0];
  return {
    thumb: info.thumburl,
    filePage: `https://commons.wikimedia.org/wiki/${encodeURIComponent((match.title || "").replace(/ /g, "_"))}`,
    license: info.extmetadata?.LicenseShortName?.value || "See source page"
  };
}

async function loadVisibleImages() {
  const wraps = [...grid.querySelectorAll(".photo-wrap")];
  for (const wrap of wraps) {
    const name = wrap.dataset.person;
    if (state.imageCache.has(name) || state.pending.has(name)) continue;
    state.pending.add(name);

    try {
      const image = await findCommonsImage(name);
      if (image) {
        state.imageCache.set(name, image);
        const currentWrap = [...grid.querySelectorAll(".photo-wrap")]
          .find(el => el.dataset.person === name);
        if (currentWrap) showImage(currentWrap, image);
      }
    } catch (error) {
      console.warn(`Could not load Wikimedia Commons image for ${name}:`, error);
    } finally {
      state.pending.delete(name);
    }
  }
}

searchInput.addEventListener("input", event => {
  state.query = event.target.value;
  state.visible = PAGE_SIZE;
  render();
});

document.getElementById("clearSearch").addEventListener("click", () => {
  searchInput.value = "";
  state.query = "";
  state.visible = PAGE_SIZE;
  render();
  searchInput.focus();
});

document.querySelectorAll(".filter-chip").forEach(button => {
  button.addEventListener("click", () => {
    document.querySelector(".filter-chip.selected")?.classList.remove("selected");
    button.classList.add("selected");
    state.category = button.dataset.category;
    state.visible = PAGE_SIZE;
    render();
  });
});

loadMore.addEventListener("click", () => {
  state.visible += PAGE_SIZE;
  render();
});

document.addEventListener("keydown", event => {
  if ((event.metaKey || event.ctrlKey) && event.key.toLowerCase() === "k") {
    event.preventDefault();
    searchInput.focus();
  }
});

document.getElementById("year").textContent = new Date().getFullYear();
if (apiNotice) apiNotice.hidden = true;
render();

